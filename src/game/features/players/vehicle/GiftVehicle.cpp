	// the garage also refuses vehicles modded by another player, driven by a second player, test drives and
	// MPBitset bits 19 and 20, so those marks are removed
	class GiftVehicle : public PlayerCommand
	{
		using PlayerCommand::PlayerCommand;

		static constexpr float MaxDistance = 10.0f;

		// the vehicle the player is in, or the closest one near them without a driver
		static Vehicle FindVehicle(Ped ped)
		{
			if (auto veh = ped.GetVehicle())
				return veh;

			auto pos = ped.GetPosition();
			Vehicle closest = nullptr;
			float closestDistance = MaxDistance;
			for (auto veh : Pools::GetVehicles())
			{
				if (!veh || VEHICLE::GET_PED_IN_VEHICLE_SEAT(veh.GetHandle(), -1, false))
					continue;

				float distance = veh.GetPosition().GetDistance(pos);
				if (distance < closestDistance)
				{
					closest = veh;
					closestDistance = distance;
				}
			}
			return closest;
		}

		virtual void OnCall(Player player) override
		{
			auto ped = player.GetPed();
			if (!ped)
				return;

			auto veh = FindVehicle(ped);
			if (!veh)
			{
				Notifications::Show("Gift Vehicle", std::format("No vehicle near {}", player.GetName()), NotificationType::Error);
				return;
			}

			static ScriptFunction isVehicleValidForPV("freemode"_J, ScriptPointer("IsVehicleValidForPV", "5D ? ? ? 2A 06 56 13 00 38 00").Add(1).Rip());
			if (!isVehicleValidForPV.Call<bool>(veh.GetModel()))
			{
				Notifications::Show("Gift Vehicle", "This vehicle can't be stored in a garage", NotificationType::Error);
				return;
			}

			if (g_MustPurchaseVehicles.contains(veh.GetModel()))
			{
				Notifications::Show("Gift Vehicle", std::format("The {} has to be bought to be stored, use a street model", veh.GetFullName()), NotificationType::Error);
				return;
			}

			auto handle = veh.GetHandle();
			if (DECORATOR::DECOR_EXIST_ON(handle, "Player_Vehicle"))
			{
				Notifications::Show("Gift Vehicle", "This is a personal vehicle", NotificationType::Error);
				return;
			}

			if (!veh.RequestControl())
			{
				Notifications::Show("Gift Vehicle", "Couldn't take control of the vehicle", NotificationType::Error);
				return;
			}

			DECORATOR::DECOR_REMOVE(handle, "Veh_Modded_By_Player");
			DECORATOR::DECOR_REMOVE(handle, "Not_Allow_As_Saved_Veh");
			DECORATOR::DECOR_REMOVE(handle, "TestDrive");
			if (DECORATOR::DECOR_EXIST_ON(handle, "MPBitset"))
				DECORATOR::DECOR_SET_INT(handle, "MPBitset", DECORATOR::DECOR_GET_INT(handle, "MPBitset") & ~((1 << 19) | (1 << 20)));

			Notifications::Show("Gift Vehicle", std::format("{} can now store the {} in a personal garage. Don't drive it yourself first", player.GetName(), veh.GetFullName()));
		}
	};

